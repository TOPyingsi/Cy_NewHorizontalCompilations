export function getEnemyTier(enemy: CDXX2_ENEMY): number {
    if (enemy <= CDXX2_ENEMY.圆满妖兽) return CDXX2_ENEMY_TIER.妖兽;
    if (enemy <= CDXX2_ENEMY.圆满灵兽) return CDXX2_ENEMY_TIER.灵兽;
    if (enemy <= CDXX2_ENEMY.圆满仙兽) return CDXX2_ENEMY_TIER.仙兽;
    if (enemy <= CDXX2_ENEMY.圆满圣兽) return CDXX2_ENEMY_TIER.圣兽;
    if (enemy <= CDXX2_ENEMY.圆满帝兽) return CDXX2_ENEMY_TIER.帝兽;
    return CDXX2_ENEMY_TIER.神兽;
}

